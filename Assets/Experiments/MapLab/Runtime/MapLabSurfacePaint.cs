using UnityEngine;

namespace KingdomSurvival.MapLab
{
    // Поверхность поверх луга в базовом слое покраски (боевая арена: лёд,
    // грязь, снег, огонь…): цвет подмешивается до мазков, и мазки кисти
    // кладутся уже им — поверхность нарисована той же манерой, что поле.
    // Вызывается из фоновых потоков покраски: реализация только читает свой
    // неизменяемый снимок.
    public interface IMapLabSurfacePaint
    {
        // world — точка земли (x, z); color — цвет луга, меняется на месте.
        // owns — точка внутри поверхности (мазки этой точки — её цветом).
        // false — поверхности рядом нет.
        bool Apply(Vector2 world, MapLabPalette palette, ref Color color, out bool owns);
    }
}
